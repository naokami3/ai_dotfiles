#!/usr/bin/env python3
"""ファイル一覧（files.json）を作る。言語に依存しない。

対象リポジトリの追跡ファイル（git ls-files。git でなければ全走査）から、
生成物・ロックファイル・バイナリ・minify 済み・巨大データを除外し、
残りを役割（source / config / test / doc）に分類して行数とハッシュを記録する。
内容が完全に同じファイルは2件目以降を dup_of で正規ファイルに寄せる（読むのは1回で済む）。

使い方:
    python3 build_file_manifest.py --repo <対象リポジトリ> --work <作業ディレクトリ>
        [--exclude GLOB]... [--include GLOB]... [--subdir DIR]

--exclude  追加で除外する glob（例: 'legacy/**'）
--include  既定の除外ルールより優先して含める glob
--subdir   モノレポの一部だけを対象にする場合のサブディレクトリ
標準出力には要約だけを出す（全件は files.json を参照）。
"""
import argparse
import collections
import os
import subprocess
import sys
from datetime import datetime, timezone

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _common import GlobSet, decode_bytes, die, save_json, sha1_bytes, split_lines, work_paths  # noqa: E402

DEFAULT_EXCLUDES = [
    # 依存・ビルド成果物
    "**/node_modules/**", "**/vendor/**", "**/.venv/**", "**/venv/**", "**/site-packages/**",
    "**/dist/**", "**/build/**", "**/.next/**", "**/.nuxt/**", "**/coverage/**",
    "**/__pycache__/**", "**/target/**", "**/obj/**", "**/.git/**",
    # ロックファイル
    "**/package-lock.json", "**/yarn.lock", "**/pnpm-lock.yaml", "**/poetry.lock", "**/uv.lock",
    "**/Pipfile.lock", "**/Cargo.lock", "**/go.sum", "**/composer.lock", "**/Gemfile.lock",
    "**/bun.lockb",
    # 生成物・アセット
    "**/*.min.js", "**/*.min.css", "**/*.map", "**/*.snap", "**/*.svg", "**/*.ico",
    "**/*_pb2.py", "**/*_pb2_grpc.py", "**/*.pb.go", "**/*.generated.*", "**/*.g.dart",
    "**/*.lock", "**/*.log",
]

# 先頭2行にある、ツールが出力する定型句だけを生成物とみなす（業務コメントの単語で誤除外しないため）
GENERATED_MARKERS = ("@generated", "do not edit", "code generated by", "this file was automatically generated",
                     "this file is automatically generated", "this file is auto-generated",
                     "this file was auto-generated", "auto-generated file", "autogenerated file",
                     "generated by the protocol buffer")

TEST_GLOBS = GlobSet([
    "**/test/**", "**/tests/**", "**/__tests__/**", "**/spec/**", "**/e2e/**",
    "**/test_*.py", "**/*_test.py", "**/*_test.go", "**/*.test.*", "**/*.spec.*", "**/*_spec.rb",
    "**/conftest.py", "**/*Test.java", "**/*Tests.cs",
])
# doc は拡張子で判定する（docs/ 配下のコードや、Next.js の app/ 配下の .mdx ページを doc にしないため）
DOC_GLOBS = GlobSet(["**/*.md", "**/*.mdx", "**/*.rst", "**/*.txt", "**/*.adoc",
                     "**/LICENSE*", "**/CHANGELOG*"])
PAGE_DOC_GLOBS = GlobSet(["**/app/**/*.mdx", "**/pages/**/*.mdx", "**/routes/**/*.mdx"])
CONFIG_GLOBS = GlobSet(["**/*.json", "**/*.yaml", "**/*.yml", "**/*.toml", "**/*.ini", "**/*.cfg",
                        "**/*.conf", "**/*.env.example", "**/.env.*", "**/Dockerfile*",
                        "**/docker-compose*", "**/Makefile", "**/*.xml", "**/*.properties",
                        "**/*.tf", "**/*.hcl"])
REQ_GLOBS = GlobSet(["**/requirements*.txt", "**/constraints*.txt"])
DATA_EXTS = (".json", ".csv", ".tsv", ".yaml", ".yml", ".xml")
LARGE_DATA_LINES = 2000


def list_files(repo):
    try:
        out = subprocess.run(["git", "-C", repo, "ls-files", "-z"], capture_output=True, check=True)
        files = [p for p in out.stdout.decode("utf-8", "replace").split("\0") if p]
        commit = subprocess.run(["git", "-C", repo, "rev-parse", "HEAD"], capture_output=True,
                                text=True).stdout.strip() or None
        untracked = subprocess.run(["git", "-C", repo, "ls-files", "--others", "--exclude-standard", "-z"],
                                   capture_output=True).stdout.decode("utf-8", "replace").split("\0")
        return files, commit, [u for u in untracked if u]
    except (subprocess.CalledProcessError, FileNotFoundError):
        files = []
        for root, dirs, names in os.walk(repo):
            dirs[:] = [d for d in dirs if d != ".git"]
            for n in names:
                files.append(os.path.relpath(os.path.join(root, n), repo).replace(os.sep, "/"))
        return files, None, []


def classify(path):
    if TEST_GLOBS.match(path):
        return "test"
    if REQ_GLOBS.match(path):
        return "config"
    if PAGE_DOC_GLOBS.match(path):
        return "source"
    if DOC_GLOBS.match(path):
        return "doc"
    if CONFIG_GLOBS.match(path):
        return "config"
    return "source"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", required=True)
    ap.add_argument("--work", required=True)
    ap.add_argument("--exclude", action="append", default=[])
    ap.add_argument("--include", action="append", default=[])
    ap.add_argument("--subdir")
    a = ap.parse_args()

    repo = os.path.abspath(a.repo)
    default_ex, extra_ex, inc = GlobSet(DEFAULT_EXCLUDES), GlobSet(a.exclude), GlobSet(a.include)
    paths, commit, untracked = list_files(repo)
    if a.subdir:
        prefix = a.subdir.strip("/") + "/"
        paths = [p for p in paths if p.startswith(prefix)]
        untracked = [p for p in untracked if p.startswith(prefix)]
    if not paths:
        die("対象ファイルが 0 件（--repo が git 管理外のサブディレクトリ、または --subdir の誤りでないか）")

    files, excluded, by_hash = [], [], {}
    for p in sorted(paths):
        full = os.path.join(repo, p)
        if not os.path.isfile(full):
            continue
        if extra_ex.match(p):
            excluded.append({"path": p, "reason": "user_exclude"})
            continue
        if default_ex.match(p) and not inc.match(p):
            excluded.append({"path": p, "reason": "default_exclude"})
            continue
        with open(full, "rb") as f:
            raw = f.read()
        if b"\0" in raw[:8192]:
            excluded.append({"path": p, "reason": "binary"})
            continue
        text, enc = decode_bytes(raw)
        lines = split_lines(text)
        n = len(lines)
        forced = inc.match(p)
        if not forced:
            head = "\n".join(lines[:2]).lower()
            if any(m in head for m in GENERATED_MARKERS):
                excluded.append({"path": p, "reason": "generated_marker", "lines": n})
                continue
            if n and (len(text) / n > 250 or max(len(l) for l in lines) > 5000):
                excluded.append({"path": p, "reason": "minified_or_long_lines", "lines": n})
                continue
            if p.lower().endswith(DATA_EXTS) and n > LARGE_DATA_LINES:
                excluded.append({"path": p, "reason": "large_data", "lines": n})
                continue
        if n == 0:
            excluded.append({"path": p, "reason": "empty"})
            continue
        h = sha1_bytes(raw)
        entry = {"path": p, "lines": n, "role": classify(p), "sha1": h}
        if enc != "utf-8":
            entry["encoding"] = enc
        if h in by_hash:
            entry["dup_of"] = by_hash[h]
        else:
            by_hash[h] = p
        files.append(entry)

    wp = work_paths(a.work)
    save_json(wp["files"], {
        "repo": repo, "commit": commit, "subdir": a.subdir,
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "exclude": a.exclude, "include": a.include,
        "files": files, "excluded": excluded,
    })

    # 要約（ここだけを読めば Phase 0 の判断ができる量に抑える）
    role = collections.Counter()
    role_lines = collections.Counter()
    ext_lines = collections.Counter()
    top_lines = collections.Counter()
    dups = 0
    for f in files:
        if "dup_of" in f:
            dups += 1
            continue
        role[f["role"]] += 1
        role_lines[f["role"]] += f["lines"]
        ext_lines[os.path.splitext(f["path"])[1] or "(なし)"] += f["lines"]
        top_lines[f["path"].split("/")[0] if "/" in f["path"] else "(root)"] += f["lines"]
    print(f"files.json を出力: {wp['files']}")
    print(f"commit: {commit}")
    print(f"対象 {len(files)} ファイル（重複 {dups} 件は正規ファイルに寄せる）/ 除外 {len(excluded)} ファイル")
    print("役割別: " + ", ".join(f"{r} {role[r]}件 {role_lines[r]}行" for r in sorted(role)))
    print("拡張子別（行数上位15）: " + ", ".join(f"{e} {n}" for e, n in ext_lines.most_common(15)))
    print("トップディレクトリ別（行数上位20）: " + ", ".join(f"{d} {n}" for d, n in top_lines.most_common(20)))
    reasons = collections.Counter(e["reason"] for e in excluded)
    print("除外理由: " + ", ".join(f"{r} {n}" for r, n in reasons.most_common()))
    ex_dirs = collections.Counter()
    for e in excluded:
        if e["reason"] in ("default_exclude", "generated_marker", "minified_or_long_lines", "large_data"):
            d = e["path"].rsplit("/", 1)[0] if "/" in e["path"] else "(root)"
            ex_dirs[(d, e["reason"])] += 1
    if ex_dirs:
        print("除外したディレクトリ（件数上位30。業務コードが混ざっていないか必ず確認する）:")
        for (d, r), n in ex_dirs.most_common(30):
            print(f"  {d}/ ({r}) {n}件")
    big = sorted((f for f in files if "dup_of" not in f), key=lambda f: -f["lines"])[:20]
    print("行数の多い対象ファイル上位20（シード・ダンプ・翻訳データ等なら --exclude を検討）:")
    for f in big:
        print(f"  {f['path']} ({f['role']}, {f['lines']}行)")
    encs = collections.Counter(f.get("encoding", "utf-8") for f in files)
    if set(encs) != {"utf-8"}:
        print("文字コード: " + ", ".join(f"{k} {n}" for k, n in encs.most_common()))
    if untracked:
        print(f"※ git 未追跡のファイル {len(untracked)} 件は対象外（未コミットの新規ファイルがないか確認する）: "
              + " ".join(untracked[:10]) + (" ..." if len(untracked) > 10 else ""))


if __name__ == "__main__":
    main()
